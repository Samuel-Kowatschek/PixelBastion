/** Baut aus einem Pixel-Array eine Offscreen-Canvas. map: Platzhalter -> Palettenindex. */
export function buildSprite(rows, map = {}) {
  const h = rows.length, w = rows[0].length;
  const c = document.createElement('canvas');
  c.width = w; c.height = h;
  const g = c.getContext('2d');
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      const ch = rows[y][x];
      if (ch === '.' || ch === undefined) continue;
      let idx = map[ch] !== undefined ? map[ch] : parseInt(ch, 16);
      if (Number.isNaN(idx)) continue;
      g.fillStyle = PAL[idx];
      g.fillRect(x, y, 1, 1);
    }
  }
  return c;
}

/** Einfarbige Silhouette (z. B. weißes Aufblitzen bei Treffer). */
export function buildSilhouette(rows, colorIdx) {
  const h = rows.length, w = rows[0].length;
  const c = document.createElement('canvas');
  c.width = w; c.height = h;
  const g = c.getContext('2d');
  g.fillStyle = PAL[colorIdx];
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) if (rows[y][x] !== '.') g.fillRect(x, y, 1, 1);
  return c;
}
